# txt_to_md_minimal.py

from pathlib import Path
from langchain_openai import ChatOpenAI
from dotenv import load_dotenv


load_dotenv()

# === 1. OpenAI Key 직접 입력 ===

llm = ChatOpenAI(model="gpt-4o-mini", temperature=0)

# === 2. 프롬프트 ===
SYSTEM_PROMPT = """
너는 설문지 TXT를 구조화된 Markdown으로 변환하는 전처리 엔진이다.

────────────────────────
[목표]
────────────────────────
- 문항, 보기, 스킵 로직의 구조를 명확히 계층화한다.
- 특히 "스킵-보기 결속"을 절대적으로 강제한다.
- 의미는 절대 변경하지 않는다.
- 추론하지 않는다.
- 출력은 Markdown만 한다.

────────────────────────
[문항 구조 규칙]
────────────────────────
1. ===== PAGE N ===== → ## PAGE N
2. 문항번호 (A1, B1-2, C3 등)는 반드시 ### 헤더로 작성한다.
3. 보기(①②③ 등)는 반드시 다음 형식으로 작성한다:

   - ① 보기내용
   - ② 보기내용

4. 보기 번호는 절대 한 줄에 여러 개 쓰지 마라.
   ❌ ① ... ② ...
   ⭕ - ① ...
      - ② ...

────────────────────────
[스킵-보기 결속 강제 규칙] ★★★★★
────────────────────────

1. 스킵 문장(☞, ⇒, →, 이동, 건너뛰 등 포함 문장)은
   반드시 해당 보기 바로 아래에만 위치해야 한다.

2. 스킵은 항상 다음 형식으로 출력한다:

      > [skip] 원문 그대로

3. 스킵은 절대 독립적으로 존재하면 안 된다.
   (보기 없이 skip가 연속 등장 금지)

4. 여러 개의 skip 문장이 연속 등장하는 경우,
   반드시 직전 보기 하나에만 귀속시킨다.

5. 보기 번호가 명시된 스킵은 반드시 해당 번호의 보기 아래에 배치한다.

   예:
   "(C2-1로 이동)" → C2의 특정 보기와 연결된 경우,
   해당 보기 바로 아래에만 배치한다.

6. TXT에서 스킵이 보기와 같은 줄에 존재하면,
   반드시 분리하고 해당 보기 아래에 재배치한다.

────────────────────────
[하위문항 기반 재배치 규칙]
────────────────────────

스킵 문장에 다음과 같은 표현이 포함된 경우:

- (B1-1만 응답 후 ...)
- (B1-2 응답 후 ...)
- (C3-1 응답 후 ...)
- (~번 선택 시 ...)

이때:

1. 하위문항 번호의 부모 문항을 찾는다.
2. 그 부모 문항의 보기 중 해당 하위문항을 유발하는 보기 아래에 배치한다.
3. 절대 여러 보기 아래에 동시에 배치하지 마라.

────────────────────────
[중요 금지 규칙]
────────────────────────

- 하나의 skip를 두 개 이상의 보기 아래에 복제하지 마라.
- 스킵을 문항 전체 조건처럼 위로 올리지 마라.
- 보기와 무관한 위치에 skip를 배치하지 마라.
- 의미를 추론해서 재작성하지 마라.

────────────────────────
[출력 제약]
────────────────────────
- Markdown만 출력한다.
- 코드블록 금지.
- 설명 금지.
- 주석 금지.
"""

# === 3. TXT 읽기 ===
text = Path("output/한국생산기술연구원_중.txt").read_text(encoding="utf-8")

# === 4. LLM 호출 ===
response = llm.invoke([
    ("system", SYSTEM_PROMPT),
    ("human", text),
])

markdown = response.content

# === 5. Markdown 파일 생성 ===
Path("output/한국생산기술연구원_중.md").write_text(markdown, encoding="utf-8")

print("완료: md 생성됨")